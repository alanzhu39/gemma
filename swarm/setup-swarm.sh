#!/usr/bin/env bash
# Creates one SwarmChat identity per agent and writes a ready-to-use env file.
#
#   swarm/setup-swarm.sh [server-url]
#
# Tokens are written to swarm/.env.local, which is gitignored: they are secrets
# for this local server, not project configuration.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DATA_DIR="${SWARMCHAT_DATA:-/tmp/swarm-data}"
SERVER="${1:-http://127.0.0.1:8484}"
ENV_FILE="$HERE/.env.local"

AGENTS=(
	"orchestrator:Orchestrator"
	"profiler:Profiler"
	"kernel:Kernel Dev"
	"integrator:Integrator"
)

mkdir -p "$HERE"

if ! curl -sf -m 5 -o /dev/null "$SERVER/"; then
	echo "SwarmChat is not reachable at $SERVER" >&2
	echo "Start it with: swarmchat serve --data $DATA_DIR" >&2
	exit 1
fi

: > "$ENV_FILE"
{
	echo "# Generated by swarm/setup-swarm.sh — do not commit"
	echo "SWARMCHAT_SERVER=$SERVER"
} >> "$ENV_FILE"

for entry in "${AGENTS[@]}"; do
	name="${entry%%:*}"
	label="${entry#*:}"
	# `admin add` prints "Added <id> (<name>). Token: <token>". If the user
	# already exists, rotate instead, which prints a fresh token.
	out="$(swarmchat admin add "$name" --name "$label" --data "$DATA_DIR" 2>/dev/null || true)"
	token="$(printf '%s' "$out" | sed -n 's/.*Token: \(.*\)$/\1/p')"
	if [ -z "$token" ]; then
		out="$(swarmchat admin rotate "$name" --data "$DATA_DIR" 2>/dev/null || true)"
		token="$(printf '%s' "$out" | sed -n 's/.*New token for [^:]*: \(.*\)$/\1/p')"
	fi
	if [ -z "$token" ]; then
		echo "could not create or read a token for $name" >&2
		exit 1
	fi
	printf 'SWARMCHAT_TOKEN_%s=%s\n' "$(echo "$name" | tr '[:lower:]' '[:upper:]')" "$token" >> "$ENV_FILE"
	echo "ok: $name"
done

# A shared channel for design discussion and one for accepted results.
export SWARMCHAT_SERVER="$SERVER"
export SWARMCHAT_TOKEN="$(sed -n 's/^SWARMCHAT_TOKEN_ORCHESTRATOR=//p' "$ENV_FILE")"
swarmchat channel create perf --public \
	--description "Gemma 3 WebGPU inference optimization: hypotheses, claims, bottlenecks" \
	>/dev/null 2>&1 || true
swarmchat channel create results --public \
	--description "Accepted measurements and verdicts only" \
	>/dev/null 2>&1 || true

echo
echo "wrote $ENV_FILE"
echo "watch the swarm with: swarmchat view --data $DATA_DIR"
