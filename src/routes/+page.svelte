<h1>Welcome!</h1>
<p>This project implements Gemma3 inference completely in your browser!</p>
<p>Specifically, we run Gemma3-270m-Instruct in FP16 on WebGPU. Built using jax-js.</p>
<p>
	Visit the Inference tab to learn more about the model architecture and explore different layer
	activations during inference.
</p>
<p>
	Visit the Performance tab to explore the impact of different optimizations like KV-caching and JIT
	compilation.
</p>
<p>Visit the Chat tab to interact with the model in a chat-like interface.</p>
